#!/usr/bin/env python3
"""Build a self-contained docker-compose.yaml for Coolify from proxy/Dockerfile and proxy/gitgate.py.

The code goes into dockerfile_inline as a heredoc, so a single file can be pasted into Coolify.
Run: python3 coolify/make_compose.py > coolify/docker-compose.yaml
"""
import sys
import textwrap
from pathlib import Path

PROXY = Path(__file__).resolve().parent.parent / "proxy"
COPY_LINE = "COPY gitgate.py /app/gitgate.py"
ENVIRONMENT = ["GITGATE_TOKEN", "GITGATE_ALLOW", "GITGATE_BRANCH_PREFIX", "GITGATE_POLICY",
               "GITGATE_ENABLE_PR", "GITGATE_PR_BASES"]


def main():
    code = (PROXY / "gitgate.py").read_text()
    dockerfile = (PROXY / "Dockerfile").read_text()
    if "PYEOF" in code or COPY_LINE not in dockerfile:
        sys.exit("make_compose: gitgate.py contains PYEOF or the Dockerfile has no COPY line for it")
    dockerfile = dockerfile.replace(COPY_LINE, f"COPY <<'PYEOF' /app/gitgate.py\n{code.rstrip()}\nPYEOF")
    inline = textwrap.indent(dockerfile.replace("$", "$$"), " " * 8)  # $$ is a literal $ for compose
    environment = "\n".join(f"      - {name}=${{{name}}}" for name in ENVIRONMENT)
    sys.stdout.write(f"""\
# Generated by coolify/make_compose.py from proxy/. Do not edit by hand.
# Set in Coolify (Environment Variables): GITGATE_TOKEN (secret), GITGATE_ALLOW and GITGATE_NETWORK
# (the existing Docker network your agent containers are on).
services:
  gitgate:
    build:
      context: .
      dockerfile_inline: |
{inline}    restart: unless-stopped
    environment:
{environment}
    networks:
      clients:
        aliases:
          - gitgate

networks:
  clients:
    name: ${{GITGATE_NETWORK}}
    external: true
""")


if __name__ == "__main__":
    main()
