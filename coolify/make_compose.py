#!/usr/bin/env python3
"""Builds a self-contained docker-compose.yaml for Coolify from proxy/gitgate.py.

The proxy code is embedded in dockerfile_inline (heredoc), so a single file can be
pasted into Coolify without a separate git repository. `$` is doubled for compose.
Run: python3 coolify/make_compose.py > coolify/docker-compose.yaml
"""
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent
code = (root / "proxy" / "gitgate.py").read_text()
assert "PYEOF" not in code
code = code.replace("$", "$$")
body = "\n".join(("        " + line) if line else "" for line in code.splitlines())

HEAD = """\
# Generated by coolify/make_compose.py from proxy/gitgate.py. Do not edit by hand.
# Set these in Coolify (Environment Variables): GITGATE_TOKEN (secret), GITGATE_ALLOW,
# GITGATE_NETWORK (name of the existing Docker network your client containers are on).
services:
  gitgate:
    build:
      context: .
      dockerfile_inline: |
        FROM python:3.13-alpine
        RUN apk add --no-cache openssl && adduser -D -u 10001 gitgate
        COPY <<'PYEOF' /app/gitgate.py
"""
TAIL = """
        PYEOF
        USER gitgate
        CMD ["python3", "-I", "/app/gitgate.py"]
    restart: unless-stopped
    environment:
      - GITGATE_TOKEN=${GITGATE_TOKEN}
      - GITGATE_ALLOW=${GITGATE_ALLOW}
      - GITGATE_BRANCH_PREFIX=${GITGATE_BRANCH_PREFIX}
      - GITGATE_POLICY=${GITGATE_POLICY}
      - GITGATE_ENABLE_PR=${GITGATE_ENABLE_PR}
      - GITGATE_PR_BASES=${GITGATE_PR_BASES}
    healthcheck:
      test: ["CMD", "python3", "-c", "import socket; socket.create_connection(('127.0.0.1', 8080), 2)"]
      interval: 30s
      timeout: 5s
      retries: 3
    networks:
      clients:
        aliases:
          - gitgate

networks:
  clients:
    name: ${GITGATE_NETWORK}
    external: true
"""
sys.stdout.write(HEAD + body + TAIL)
